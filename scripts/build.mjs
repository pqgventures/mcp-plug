#!/usr/bin/env node
// Builds the registry bundle, the browser component (ESM + global), SVG badges and the demo assets.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const write = (p, s) => { mkdirSync(dirname(join(ROOT, p)), { recursive: true }); writeFileSync(join(ROOT, p), s); };

export function loadRegistry() {
  const dir = join(ROOT, 'registry/clients');
  const clients = readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .map((f) => { const c = JSON.parse(readFileSync(join(dir, f), 'utf8')); delete c.$schema; return c; });
  const meta = JSON.parse(read('registry/order.json'));
  const ids = new Set(clients.map((c) => c.id));
  for (const id of [...meta.order, ...meta.defaults]) if (!ids.has(id)) throw new Error('order.json lists unknown client ' + id);
  const order = [...meta.order, ...clients.map((c) => c.id).filter((id) => !meta.order.includes(id)).sort()];
  return { version: JSON.parse(read('package.json')).version, updated: meta.updated, order, defaults: meta.defaults, clients };
}

function strip(src) {
  return src.split('\n')
    .filter((l) => !/^import\s/.test(l) && !/^export\s*\{/.test(l))
    .map((l) => l.replace(/^export\s+(?=(const|function|class|async)\b)/, ''))
    .join('\n');
}

export function build() {
  const registry = loadRegistry();
  // The component shows the curated defaults unless clients="..." is set.
  // The browser bundle only carries what the widget renders (no sources, notes or auth details).
  const slim = registry.clients.map(({ sources, notes, confidence, vendor, auth, ...c }) => ({ ...c, auth: { oauth: auth.oauth, dcr: auth.dcr, cimd: auth.cimd } }));
  write('src/registry.data.js', '// Generated by scripts/build.mjs from registry/. Do not edit.\nexport const REGISTRY = ' + JSON.stringify({ ...registry, clients: slim, order: registry.defaults, all: registry.order }) + ';\n');
  write('dist/registry.json', JSON.stringify(registry, null, 2) + '\n');

  const body = [strip(read('src/core.js')), strip(read('src/registry.data.js')), strip(read('src/element.js'))].join('\n');
  const banner = '/*! mcp-plug v' + registry.version + ' | MIT | https://github.com/pqgventures/mcp-plug */\n';
  const allFix = '\n';
  const esm = banner + body + allFix + 'define();\nexport { plan, render, normalizeServer, badges, REGISTRY, VERSION, TEXTS, McpPlugElement, define };\n';
  const iife = banner + '(function(){\n' + body + allFix + 'define();\nglobalThis.MCPPlug = { plan, render, normalizeServer, badges, REGISTRY, VERSION, TEXTS, McpPlugElement, define };\n})();\n';
  write('dist/mcp-plug.js', esm);
  write('dist/mcp-plug.global.js', iife);

  // Badges: one SVG per client, "Add to <Client>".
  for (const c of registry.clients) write('dist/badges/' + c.id + '.svg', badge(c));

  for (const f of ['mcp-plug.js', 'mcp-plug.global.js', 'registry.json']) copyFileSync(join(ROOT, 'dist', f), join(ROOT, 'docs', f));
  mkdirSync(join(ROOT, 'docs/badges'), { recursive: true });
  for (const c of registry.clients) copyFileSync(join(ROOT, 'dist/badges', c.id + '.svg'), join(ROOT, 'docs/badges', c.id + '.svg'));
  copyFileSync(join(ROOT, 'registry/schema.json'), join(ROOT, 'docs/schema.json'));
  write('docs/open-schemes.json', JSON.stringify(schemes(registry)) + '\n');
  write('CLIENTS.md', clientsTable(registry, 'en'));
  write('CLIENTS.pt-BR.md', clientsTable(registry, 'pt'));
  return registry;
}

function clientsTable(registry, lang) {
  const yn = (v) => (v === true ? '✓' : v === false ? '—' : '?');
  const head = lang === 'pt'
    ? '# Clientes\n\nGerado de `registry/clients/` por `npm run build`. Não edite à mão. [English](CLIENTS.md)\n\n| App | Um clique | Remoto (HTTP) | Local (stdio) | OAuth | Planos | Conferido |\n| --- | --- | --- | --- | --- | --- | --- |\n'
    : '# Clients\n\nGenerated from `registry/clients/` by `npm run build`. Do not edit by hand. [Português](CLIENTS.pt-BR.md)\n\n| App | One click | Remote (HTTP) | Local (stdio) | OAuth | Plans | Checked |\n| --- | --- | --- | --- | --- | --- | --- |\n';
  const rows = registry.order.map((id) => {
    const c = registry.clients.find((x) => x.id === id);
    const link = c.methods.find((m) => m.oneClick);
    const oauth = c.auth.oauth ? [c.auth.dcr ? 'DCR' : null, c.auth.cimd ? 'CIMD' : null, c.auth.pkce ? 'PKCE' : null].filter(Boolean).join(', ') || '✓' : yn(c.auth.oauth);
    return '| [' + c.name + '](registry/clients/' + c.id + '.json) | ' + (link ? '✓' : '—') + ' | ' + yn(c.transports.http) + ' | ' + yn(c.transports.stdio) + ' | ' + oauth + ' | ' + c.plans[lang].replace(/\\|/g, '/').replace(/\\*\\*/g, '') + ' | ' + c.verified + ' |';
  });
  return head + rows.join('\n') + '\n';
}

// App schemes that docs/open.html may forward to (GitHub strips non-https links from READMEs).
function schemes(registry) {
  const set = new Set();
  for (const c of registry.clients) for (const m of c.methods) {
    if (m.kind !== 'link' || !m.template) continue;
    const mm = m.template.match(/^([a-z][a-z0-9+.-]*:(\/\/)?[^{?]*)/i);
    if (mm && !/^https?:/i.test(mm[1])) set.add(mm[1]);
  }
  return [...set].sort();
}

function textWidth(s) {
  let w = 0;
  for (const ch of s) w += /[ilj.,:;'|!]/.test(ch) ? 3.4 : /[mwMW]/.test(ch) ? 9.6 : /[A-Z]/.test(ch) ? 7.6 : 6.5;
  return Math.round(w);
}

export function badge(c, left = 'Add to') {
  const color = c.color || '#374151';
  const lw = textWidth(left) + 20, rw = textWidth(c.name) + 20, w = lw + rw;
  const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
  return '<svg xmlns="http://www.w3.org/2000/svg" width="' + w + '" height="28" role="img" aria-label="' + esc(left + ' ' + c.name) + '">'
    + '<title>' + esc(left + ' ' + c.name) + '</title>'
    + '<clipPath id="r"><rect width="' + w + '" height="28" rx="6"/></clipPath><g clip-path="url(#r)">'
    + '<rect width="' + lw + '" height="28" fill="#1f2328"/><rect x="' + lw + '" width="' + rw + '" height="28" fill="' + color + '"/></g>'
    + '<g fill="#fff" font-family="-apple-system,Segoe UI,Helvetica,Arial,sans-serif" font-size="12" font-weight="600">'
    + '<text x="10" y="18">' + esc(left) + '</text><text x="' + (lw + 10) + '" y="18">' + esc(c.name) + '</text></g></svg>\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const r = build();
  console.log('built ' + r.clients.length + ' clients, v' + r.version);
}

